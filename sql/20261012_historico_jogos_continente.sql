-- Preserva classificações preenchidas manualmente; completa apenas ausentes.
UPDATE public.historico_jogos
SET continente = public.historico_continente_por_pais(pais)
WHERE NULLIF(btrim(continente), '') IS NULL
  AND public.historico_continente_por_pais(pais) IS NOT NULL;

-- Mantém continente preenchido para novos jogos. Se pais mudar, reclassifica.
CREATE OR REPLACE FUNCTION public.historico_jogos_definir_continente()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.pais IS DISTINCT FROM OLD.pais THEN
    NEW.continente := public.historico_continente_por_pais(NEW.pais);
  ELSIF NULLIF(btrim(NEW.continente), '') IS NULL THEN
    NEW.continente := public.historico_continente_por_pais(NEW.pais);
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_historico_jogos_continente ON public.historico_jogos;
CREATE TRIGGER trg_historico_jogos_continente
BEFORE INSERT OR UPDATE OF pais, continente ON public.historico_jogos
FOR EACH ROW EXECUTE FUNCTION public.historico_jogos_definir_continente();

-- Distribuição para validar a migração:
SELECT COALESCE(continente,'Não informado') AS continente,
       COUNT(*) AS jogos
FROM public.historico_jogos
GROUP BY 1 ORDER BY 1;

-- Países ainda não mapeados (atribuir depois, sem classificar por suposição):
SELECT pais, COUNT(*) AS jogos
FROM public.historico_jogos
WHERE continente IS NULL
GROUP BY pais ORDER BY jogos DESC;
