CREATE SCHEMA IF NOT EXISTS backtest_apostas;
-- statement
CREATE TABLE IF NOT EXISTS backtest_apostas.paises (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    continente TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- statement
CREATE UNIQUE INDEX IF NOT EXISTS ux_paises_nome_lower
    ON backtest_apostas.paises ((LOWER(nome)));
-- statement
CREATE TABLE IF NOT EXISTS backtest_apostas.campeonatos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pais_id BIGINT NOT NULL REFERENCES backtest_apostas.paises(id) ON DELETE RESTRICT,
    nome TEXT NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- statement
CREATE UNIQUE INDEX IF NOT EXISTS ux_campeonatos_pais_nome_lower
    ON backtest_apostas.campeonatos (pais_id, (LOWER(nome)));
-- statement
CREATE TABLE IF NOT EXISTS backtest_apostas.clubes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pais_id BIGINT NOT NULL REFERENCES backtest_apostas.paises(id) ON DELETE RESTRICT,
    nome TEXT NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
-- statement
CREATE UNIQUE INDEX IF NOT EXISTS ux_clubes_pais_nome_lower
    ON backtest_apostas.clubes (pais_id, (LOWER(nome)));
-- statement
CREATE TABLE IF NOT EXISTS backtest_apostas.clubes_campeonatos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clube_id BIGINT NOT NULL REFERENCES backtest_apostas.clubes(id) ON DELETE CASCADE,
    campeonato_id BIGINT NOT NULL REFERENCES backtest_apostas.campeonatos(id) ON DELETE CASCADE,
    temporada TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (clube_id, campeonato_id, temporada)
);
-- statement
CREATE INDEX IF NOT EXISTS ix_clubes_campeonatos_temporada
    ON backtest_apostas.clubes_campeonatos (temporada, campeonato_id);
-- statement
CREATE TABLE IF NOT EXISTS backtest_apostas.valores_mercado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temporada TEXT NOT NULL,
    pais_id BIGINT NOT NULL REFERENCES backtest_apostas.paises(id) ON DELETE RESTRICT,
    campeonato_id BIGINT NOT NULL REFERENCES backtest_apostas.campeonatos(id) ON DELETE RESTRICT,
    clube_id BIGINT NOT NULL REFERENCES backtest_apostas.clubes(id) ON DELETE RESTRICT,
    moeda CHAR(3) NOT NULL CHECK (moeda IN ('EUR', 'USD', 'BRL')),
    valor NUMERIC(20,2) NOT NULL CHECK (valor >= 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (temporada, campeonato_id, clube_id)
);
-- statement
CREATE INDEX IF NOT EXISTS ix_valores_mercado_temporada
    ON backtest_apostas.valores_mercado (temporada, campeonato_id, clube_id);
